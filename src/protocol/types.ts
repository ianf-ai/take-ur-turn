/**
 * Per-task cast: role → agent route, a ROUTING parameter
 * only — it tells the launcher which agent to raise for each role. Not a
 * participation roster (write freedom unchanged) and NOT consumed by
 * derivation (state-machine input signature untouched). Partial maps are
 * legal: missing roles fall back to the default lineup. Immutable in meta
 * after create, same as flow. Bare strings remain the on-disk compatibility
 * shape; parameterized commands use {agent,args}.
 */
export type Cast = Partial<Record<"architect" | "executor" | "reviewer", AgentRoute>>;

export type WaitingFor = "human" | "none" | `agent:${string}`;

/** Payload envelope + extension fields the plan consumes. */
export interface Payload {
  summary: string;
  body: string;
  /** Review only. Missing/invalid verdict ⇒ no transition + needs_attention — never a write rejection (write-free principle). */
  verdict?: Verdict;
  commits?: string[];
  ref_version?: number;
  /** Note with ack === true clears warnings accumulated so far (preceding records only). */
  ack?: boolean;
  /** Decision only: the value of a human decision. */
  decision?: "approve" | "reject" | "close";
  /** Optional per-item exit-condition verdicts consumed by the record lint:
   *  canonical value is an ExitConditionVerdict array; any other legal JSON
   *  value is stored verbatim and diagnosed read-side. Explicitly unknown so
   *  miswritten material keeps saving — never a fallback source. */
  exit_conditions?: unknown;
  /** Envelope is extend-only; derive ignores fields it does not consume. */
  [key: string]: unknown;
}

/** Single record. Named ContextRecord to avoid shadowing TS's built-in Record<K, V>. */
export interface ContextRecord {
  /** Starts at 1 and increments; create produces no record (version 0). */
  version: number;
  task_id: string;
  role: string;
  agent?: string;
  model?: string;
  content_type: ContentType;
  /** ISO 8601 UTC, generated by store on append; derive never consumes it (stays out of the contract). */
  timestamp: string;
  payload: Payload;
  /** Serving build's package.json version, stamped by the store on append
   *  (additive). Absent on records written before the
   *  field existed and on recovered copies (verbatim bytes) — read and
   *  derive never require it. Approximate in a dev checkout: one manifest
   *  version covers uncommitted changes, no git-level precision. */
  tut_version?: string;
}

/**
 * Warning code vocabulary: transition warnings plus Store diagnostic overlays.
 * Warnings retain {version, code}; diagnostic overlays may add an explanatory message.
 */
export type WarningCode =
  | "OUT_OF_TABLE" // record does not fit current state: no fold, needs_attention
  | "CLOSED_ABSORB" // non-note/non-close record after closed: stays closed + needs_attention
  | "INVALID_VERDICT" // review with missing/invalid verdict: no transition + needs_attention
  | "VERSION_GAP" // version skips (e.g. v1 then v3): fold by version order anyway
  | "REVIEW_EXIT_CONDITIONS_INCOMPLETE"
  | "REVIEW_SCOPE_SECTION_MISSING"
  | "EXPECTED_REVISION"
  | "NON_CANONICAL_ROLE"
  | "VERSION_DUPLICATE"; // repeated version: fold by version order anyway

/** Append-only repair suggestion; fields describe the NEW record, never an edit. */
export interface SupportedFix {
  field: string;
  instruction: string;
  example?: string | number;
  record: { role: string; content_type: string; ref_version?: number };
}

export interface Warning {
  /** Version of the record responsible for the warning. */
  version: number;
  code: WarningCode;
  message?: string;
  /** Field/section in the triggering record. */
  location?: { field: string; section?: string };
  supportedFixes?: SupportedFix[];
  /** Consecutive failed evaluations of this lint, unrelated records do not count. */
  correction?: { root_version: number; round: number; limit: 2; exhausted: boolean };
}

/** Derivation output. needs_attention is an overlay flag, not an 8th status. */
export interface DerivedState {
  status: Status;
  waiting_for: WaitingFor;
  needs_attention: boolean;
  warnings: Warning[];
}

/**
 * Exact signature of derive (frozen seam, additive flow parameter). Pure:
 * no IO, no timestamp consumption, idempotent. flow selects the transition
 * table; absent = "full" (backward compatible).
 * Returns null for project scope (task_id "project").
 */
export type DeriveFn = (
  task_id: string,
  records: readonly ContextRecord[],
  flow?: Flow,
) => DerivedState | null;

/** Error codes — mcp.ts maps these to MCP errors; message text is not part of the contract. */
export const ErrorCode = {
  TASK_NOT_FOUND: "TASK_NOT_FOUND",
  VERSION_CONFLICT: "VERSION_CONFLICT",
  VALIDATION_ERROR: "VALIDATION_ERROR",
} as const;
export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];
